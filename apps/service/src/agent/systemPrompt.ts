/** 티켓이 에이전트에게 배정됐을 때의 작업 지시. */
export function ticketTaskPrompt(ticketId: string): string {
  return `티켓 ${ticketId} 이(가) 당신에게 배정되었습니다.

먼저 get_ticket 으로 티켓 내용, 코멘트 전체, 연결된 정책 섹션, 변경안 이력을 확인하고 update_ticket_status 로 in_progress 로 옮깁니다.
그 다음 상황에 맞는 경우 하나를 따릅니다.

[A] 코멘트에 사람(문서 담당자 등)이 내린 결정이 있고, 정책서가 아직 그 결정을 반영하지 않았다
  1. 바꿔야 할 섹션을 get_policy_document 로 조회해 현재 본문과 버전을 확인합니다. 필요하면 get_policy_history 로 과거 결정도 봅니다.
  2. 결정이 여러 섹션에 걸치면 섹션마다 따로 제안합니다. 결정 범위를 넘어서 고치지 않습니다.
  3. propose_policy_change 로 변경안을 제출합니다. rationale 에는 누가 어떤 결정을 했는지 코멘트를 인용합니다.
  4. request_approval 로 승인을 요청합니다. (티켓은 Needs Approval 로 이동)
  5. 가장 최근 코멘트가 "↩️ 수정요청" 이면, 그 피드백을 반영한 새 변경안을 제출하는 것이 이번 작업입니다.

[B] 결정이 아직 없다 (조사가 필요하다)
  1. 티켓을 구현/결정하는 데 필요한 정책을 조사합니다. 연결된 섹션만 보지 말고 관련된 다른 문서도 검색합니다.
  2. 조사 결과를 add_comment 로 남깁니다. "구현 시 지켜야 할 규칙" bullet 과 인용을 적습니다. 새로 찾은 관련 섹션은 link_policy_section 으로 연결합니다.
  3. 정책 공백이나 모순을 발견하면 시스템 지침대로 policy_gap 티켓을 만들고(중복 확인 먼저), 이 티켓 코멘트에 그 번호를 적습니다.
     이 티켓 자체가 정책 공백 티켓이라면 새로 만들지 말고, 담당자가 고를 선택지를 코멘트로 정리합니다.
  4. update_ticket_status 로 in_review 로 옮겨 사람이 확인하게 합니다.

done 으로 옮기는 것과 변경안 승인은 사람의 몫입니다.
최종 답변에는 한 일을 3줄 이내로 요약하고, 마지막 줄에 "판정:" 형식을 씁니다.`;
}
